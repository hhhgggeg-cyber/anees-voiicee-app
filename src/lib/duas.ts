const norm = (s: string) =>
  s.replace(/[\u064B-\u065F\u0670\u0640]/g, "").replace(/[أإآٱ]/g, "ا").replace(/ة/g, "ه").replace(/ى/g, "ي");

export function findDua(q: string): Dua | null {
  const t = norm(q);
  let best: Dua | null = null, score = 0;
  for (const d of DUAS) {
    const s = d.keys.filter((k) => t.includes(norm(k))).length;
    if (s > score) { score = s; best = d; }
  }
  return best;
}

